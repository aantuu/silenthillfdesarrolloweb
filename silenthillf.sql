CREATE DATABASE silenthillf;

USE silenthillf;

CREATE TABLE `CONSUMIBLE` (
  `ID_Consumible` integer PRIMARY KEY NOT NULL,
  `Efecto` varchar(255) NOT NULL,
  `Nombre_Consumible` varchar(255) NOT NULL,
  `Descripcion` varchar(255) NOT NULL
);

CREATE TABLE `ARMA` (
  `ID_Arma` integer PRIMARY KEY NOT NULL,
  `Nombre_Arma` varchar(255) NOT NULL,
  `Durabilidad` varchar(255) NOT NULL,
  `Daño` varchar(255) NOT NULL,
  `Descripcion` varchar(255) NOT NULL
);

CREATE TABLE `OBJETO` (
  `ID_Objeto` integer PRIMARY KEY NOT NULL,
  `Nombre_Objeto` varchar(255) NOT NULL,
  `Tipo` varchar(255) NOT NULL,
  `Descripcion` varchar(255) NOT NULL
);

CREATE TABLE `ESPACIO` (
  `ID_Espacio` integer PRIMARY KEY NOT NULL,
  `ID_Arma` integer NOT NULL,
  `ID_Objeto` integer NOT NULL,
  `ID_Consumible` integer NOT NULL,
  `Nombre_Espacio` varchar(255) NOT NULL,
  CONSTRAINT fk_id_arma FOREIGN KEY (ID_Arma) REFERENCES ARMA(ID_Arma),
  CONSTRAINT fk_id_objeto FOREIGN KEY (ID_Objeto) REFERENCES OBJETO(ID_Objeto),
  CONSTRAINT fk_id_consumible FOREIGN KEY (ID_Consumible) REFERENCES CONSUMIBLE(ID_Consumible)
);

CREATE TABLE `INVENTARIO` (
  `ID_Inventario` integer PRIMARY KEY NOT NULL,
  `ID_Espacio` integer NOT NULL,
  CONSTRAINT fk_id_espacio FOREIGN KEY (ID_Espacio) REFERENCES ESPACIO(ID_Espacio)
);

